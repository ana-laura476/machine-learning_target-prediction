def create_model(seq_length, data_dim):
  model = Sequential()
  model.add(Dropout(0.5, input_shape=(seq_length, data_dim)))

  # Conv1D layer
  model.add(Conv1D(filters=16, kernel_size=4, strides=2, kernel_initializer='lecun_uniform', activation='selu', padding='same', use_bias=False))
  model.add(Dropout(0.2))
  model.add(Conv1D(filters=16, kernel_size=4, strides=2, kernel_initializer='lecun_uniform', activation='selu', padding='same', use_bias=False))
  model.add(Dropout(0.2))
  model.add(AveragePooling1D())

  #LSTM layers

  model.add(LSTM(units=128, go_backwards=True, return_sequences= True, recurrent_activation='sigmoid'))
  model.add(Dropout(0.1))
  model.add(LSTM(units=512, go_backwards=False, return_sequences=False, recurrent_activation='sigmoid'))
  model.add(Dropout(0.1))

  model.add(Dense(1, activation='linear', kernel_initializer='lecun_uniform',
                  bias_initializer='zeros', kernel_regularizer=regularizers.l1_l2(0, 1e-9)))

  # Compile the model
  optimizer = Adam(learning_rate=0.01)

  model.compile(loss='mean_absolute_error', optimizer=optimizer, metrics = ['mean_absolute_error'])

  return model

